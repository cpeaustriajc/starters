"""Rewrite the results block in README.md from bench/jobs/*/result.json. Stdlib only."""

import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRADER_CHECKS = {"nop", "oracle"}
START, END = "<!-- results:start -->", "<!-- results:end -->"


def template_of(job: Path) -> str:
    for trial in sorted(job.glob("*/config.json")):
        task = ROOT / json.loads(trial.read_text())["task"]["path"] / "task.toml"
        return tomllib.loads(task.read_text()).get("metadata", {}).get("template", "?")
    return "?"


def rows() -> list[dict]:
    out = []
    for path in sorted(ROOT.glob("bench/jobs/*/result.json")):
        job = json.loads(path.read_text())
        stats = job["stats"]
        for key, ev in stats["evals"].items():
            agent, _, model = key.partition("__")
            metrics = ev["metrics"][0] if ev["metrics"] else {}
            tokens = [stats.get(k) for k in ("n_input_tokens", "n_output_tokens")]
            out.append({
                "template": template_of(path.parent), "agent": agent,
                "model": "—" if model in ("", "adhoc") else model, "runs": ev["n_trials"],
                "reward": metrics.get("reward"), "verify": metrics.get("verify"),
                "e2e": metrics.get("e2e"),
                "tokens": sum(tokens) if all(t is not None for t in tokens) else None,
                "cost": stats.get("cost_usd"), "date": (job.get("finished_at") or "")[:10],
            })
    return sorted(out, key=lambda r: (r["template"], r["agent"], r["model"]))


def pct(value: float | None) -> str:
    return "—" if value is None else f"{value * 100:.0f}%"


def table(items: list[dict]) -> list[str]:
    lines = ["| template | agent | model | runs | pass rate | verify | e2e | tokens | cost | date |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in items:
        tokens = "—" if r["tokens"] is None else f"{r['tokens']:,}"
        cost = "—" if r["cost"] is None else f"${r['cost']:.2f}"
        lines.append(f"| {r['template']} | {r['agent']} | {r['model']} | {r['runs']} | "
                     f"{pct(r['reward'])} | {pct(r['verify'])} | {pct(r['e2e'])} | "
                     f"{tokens} | {cost} | {r['date']} |")
    return lines


def block(items: list[dict]) -> str:
    agents = [r for r in items if r["agent"] not in GRADER_CHECKS]
    checks = [r for r in items if r["agent"] in GRADER_CHECKS]
    lines = [START, "", "Generated by `uv run bench/report.py`. Pass rate is the mean reward "
             "(`verify` × `e2e`). `nop` and `oracle` runs are grader checks: they are listed "
             "apart and never charted.", "", "### Agent results", ""]
    if agents:
        labels = ", ".join(f'"{r["agent"]} ({r["template"]})"' for r in agents)
        bars = ", ".join(f"{(r['reward'] or 0) * 100:.0f}" for r in agents)
        # GitHub crops the default 700x500 chart; 600x260 shows whole.
        lines += ["```mermaid", "---", "config:", "  xyChart:", "    width: 600",
                  "    height: 260", "    showDataLabel: true", "---", "xychart-beta",
                  '  title "Pass rate by agent (template)"',
                  f"  x-axis [{labels}]", '  y-axis "pass rate (%)" 0 --> 100',
                  f"  bar [{bars}]", "```", "", *table(agents)]
    else:
        lines.append("No agent runs yet.")
    lines += ["", "### Grader checks", "", *(table(checks) if checks else ["None yet."]), "", END]
    return "\n".join(lines)


readme = ROOT / "README.md"
text = readme.read_text()
pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
new = block(rows())
readme.write_text(pattern.sub(lambda _: new, text) if pattern.search(text) else text.rstrip() + "\n\n" + new + "\n")
print(new)
